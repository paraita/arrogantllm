import test, { afterEach } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import request from 'supertest';
import { createApp } from '../server/index.js';
import { hashApiToken } from '../server/auth.js';
import { createMetrics } from '../server/metrics.js';
import { createStore } from '../server/store.js';
import { loadConfig } from '../server/config.js';

const API_TOKEN = 'sk-mock-test-token';
const tempDirs = [];

async function makeApp({ maxBodySize = '1mb' } = {}) {
  const dataDir = await mkdtemp(path.join(os.tmpdir(), 'fake-llm-api-'));
  tempDirs.push(dataDir);
  const store = await createStore({ dataDir });
  await store.createModel({ id: 'bright-model:7b', name: 'Bright Model 7B', active: true });
  await store.createModel({ id: 'sleeping-model:3b', name: 'Sleeping Model 3B', active: false });
  await store.createApiToken({
    id: 'test-token',
    name: 'test client',
    prefix: API_TOKEN.slice(0, 15),
    hash: hashApiToken(API_TOKEN),
    createdAt: new Date().toISOString(),
  });
  await store.setSettings({
    minDelayMs: 0,
    maxDelayMs: 0,
    streamChunkDelayMs: 0,
    thinkingEnabled: true,
    chatTemplates: ['Proudly generated by a real model. Probably.'],
    thinkingTemplates: ['I am thinking with convincing confidence.'],
  });
  const config = { ...loadConfig({}), maxBodySize };
  const metrics = createMetrics();
  const app = createApp({ config, store, metrics });
  return { app, store, metrics };
}

afterEach(async () => {
  await Promise.all(tempDirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true })));
});

test('health is public and does not count as inference traffic', async () => {
  const { app, metrics } = await makeApp();
  const response = await request(app).get('/healthz');

  assert.equal(response.status, 200);
  assert.equal(response.body.status, 'ok');
  assert.equal(metrics.summary().totalRequests, 0);
});

test('model and inference endpoints require a valid Bearer token', async () => {
  const { app } = await makeApp();
  const missing = await request(app).get('/v1/models');
  const invalid = await request(app).get('/v1/models').set('Authorization', 'Bearer wrong');

  assert.equal(missing.status, 401);
  assert.equal(missing.body.error.type, 'authentication_error');
  assert.equal(invalid.status, 401);
});

test('model listing exposes only active models in OpenAI format', async () => {
  const { app } = await makeApp();
  const response = await request(app).get('/v1/models').set('Authorization', `Bearer ${API_TOKEN}`);

  assert.equal(response.status, 200);
  assert.equal(response.body.object, 'list');
  assert.deepEqual(response.body.data.map((model) => model.id), ['bright-model:7b']);
  assert.equal(response.body.data[0].object, 'model');
});

test('chat completion returns OpenAI fields and rejects missing or inactive models', async () => {
  const { app } = await makeApp();
  const headers = { Authorization: `Bearer ${API_TOKEN}` };
  const valid = await request(app).post('/v1/chat/completions').set(headers).send({
    model: 'bright-model:7b',
    messages: [{ role: 'user', content: 'Hello there' }],
  });
  const inactive = await request(app).post('/v1/chat/completions').set(headers).send({
    model: 'sleeping-model:3b', messages: [{ role: 'user', content: 'Hello' }],
  });
  const unknown = await request(app).post('/v1/chat/completions').set(headers).send({
    model: 'does-not-exist', messages: [{ role: 'user', content: 'Hello' }],
  });

  assert.equal(valid.status, 200);
  assert.equal(valid.body.object, 'chat.completion');
  assert.equal(valid.body.model, 'bright-model:7b');
  assert.match(valid.body.choices[0].message.content, /real model/i);
  assert.match(valid.body.choices[0].message.reasoning_content, /thinking/i);
  assert.equal(valid.body.usage.total_tokens, valid.body.usage.prompt_tokens + valid.body.usage.completion_tokens);
  assert.equal(inactive.status, 404);
  assert.equal(inactive.body.error.type, 'not_found_error');
  assert.equal(unknown.status, 404);
});

test('streaming chat uses SSE chunks and terminates with DONE', async () => {
  const { app } = await makeApp();
  const response = await request(app)
    .post('/v1/chat/completions')
    .set('Authorization', `Bearer ${API_TOKEN}`)
    .set('Accept', 'text/event-stream')
    .send({ model: 'bright-model:7b', messages: [{ role: 'user', content: 'Hello' }], stream: true });

  assert.equal(response.status, 200);
  assert.match(response.headers['content-type'], /text\/event-stream/);
  assert.match(response.text, /"object":"chat\.completion\.chunk"/);
  assert.match(response.text, /reasoning_content/);
  assert.match(response.text, /data: \[DONE\]/);
});

test('required tool choice returns a schema-shaped mock call without executing it', async () => {
  const { app } = await makeApp();
  const response = await request(app)
    .post('/v1/chat/completions')
    .set('Authorization', `Bearer ${API_TOKEN}`)
    .send({
      model: 'bright-model:7b',
      messages: [{ role: 'user', content: 'Look up the weather' }],
      tools: [{ type: 'function', function: { name: 'lookup_weather', parameters: { type: 'object', properties: { location: { type: 'string' } }, required: ['location'] } } }],
      tool_choice: 'required',
    });

  assert.equal(response.status, 200);
  assert.equal(response.body.choices[0].finish_reason, 'tool_calls');
  const call = response.body.choices[0].message.tool_calls[0];
  assert.equal(call.function.name, 'lookup_weather');
  assert.equal(typeof JSON.parse(call.function.arguments).location, 'string');
});

test('Responses, legacy completions and embeddings return compatible shapes', async () => {
  const { app } = await makeApp();
  const headers = { Authorization: `Bearer ${API_TOKEN}` };
  const responses = await request(app).post('/v1/responses').set(headers).send({ model: 'bright-model:7b', input: 'Say hello' });
  const completions = await request(app).post('/v1/completions').set(headers).send({ model: 'bright-model:7b', prompt: 'Once upon a time' });
  const embeddings = await request(app).post('/v1/embeddings').set(headers).send({ model: 'bright-model:7b', input: 'hello' });

  assert.equal(responses.status, 200);
  assert.equal(responses.body.object, 'response');
  assert.ok(responses.body.output.some((item) => item.type === 'reasoning'));
  assert.equal(completions.status, 200);
  assert.equal(completions.body.object, 'text_completion');
  assert.equal(embeddings.status, 200);
  assert.equal(embeddings.body.data[0].object, 'embedding');
  assert.ok(Array.isArray(embeddings.body.data[0].embedding));
});

test('API traffic updates safe endpoint metrics without storing prompts', async () => {
  const { app, metrics } = await makeApp();
  await request(app).get('/v1/models').set('Authorization', `Bearer ${API_TOKEN}`);
  await request(app).post('/v1/chat/completions').set('Authorization', `Bearer ${API_TOKEN}`).send({
    model: 'bright-model:7b', messages: [{ role: 'user', content: 'private prompt text' }],
  });

  const summary = metrics.summary();
  assert.equal(summary.totalRequests, 2);
  assert.equal(summary.requestsByEndpoint['/v1/models'], 1);
  assert.equal(summary.requestsByEndpoint['/v1/chat/completions'], 1);
  assert.equal(JSON.stringify(summary).includes('private prompt text'), false);
});

test('invalid JSON and oversized JSON return OpenAI-shaped errors', async () => {
  const { app } = await makeApp({ maxBodySize: '64b' });
  const headers = { Authorization: `Bearer ${API_TOKEN}`, 'Content-Type': 'application/json' };
  const malformed = await request(app).post('/v1/chat/completions').set(headers).send('{not json');
  const large = await request(app).post('/v1/chat/completions').set(headers).send({ padding: 'x'.repeat(200) });

  assert.equal(malformed.status, 400);
  assert.equal(malformed.body.error.type, 'invalid_request_error');
  assert.equal(large.status, 413);
  assert.equal(large.body.error.type, 'invalid_request_error');
});
