import test, { afterEach } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import request from 'supertest';
import { createApp } from '../server/index.js';
import { waitForResponseDelay } from '../server/routes/openai.js';
import { hashApiToken } from '../server/auth.js';
import { createMetrics } from '../server/metrics.js';
import { createStore } from '../server/store.js';
import { loadConfig } from '../server/config.js';

const API_TOKEN = 'sk-mock-test-token';
const tempDirs = [];

async function makeApp({ maxBodySize = '1mb' } = {}) {
  const dataDir = await mkdtemp(path.join(os.tmpdir(), 'fake-llm-api-'));
  tempDirs.push(dataDir);
  const store = await createStore({ dataDir });
  await store.createModel({ id: 'bright-model:7b', name: 'Bright Model 7B', active: true });
  await store.createModel({ id: 'sleeping-model:3b', name: 'Sleeping Model 3B', active: false });
  await store.createApiToken({
    id: 'test-token',
    name: 'test client',
    prefix: API_TOKEN.slice(0, 15),
    hash: hashApiToken(API_TOKEN),
    createdAt: new Date().toISOString(),
  });
  await store.setSettings({
    minDelayMs: 0,
    maxDelayMs: 0,
    streamChunkDelayMs: 0,
    thinkingEnabled: true,
    chatTemplates: ['Proudly generated by a real model. Probably.'],
    thinkingTemplates: ['I am thinking with convincing confidence.'],
  });
  const config = { ...loadConfig({}), maxBodySize };
  const metrics = createMetrics();
  const app = createApp({ config, store, metrics });
  return { app, store, metrics };
}

afterEach(async () => {
  await Promise.all(tempDirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true })));
});

test('health is public and does not count as inference traffic', async () => {
  const { app, metrics } = await makeApp();
  const response = await request(app).get('/healthz');

  assert.equal(response.status, 200);
  assert.equal(response.body.status, 'ok');
  assert.equal(metrics.summary().totalRequests, 0);
});

test('built dashboard and static assets are served by the same HTTP app', async () => {
  const dataDir = await mkdtemp(path.join(os.tmpdir(), 'fake-llm-ui-data-'));
  const webDirectory = await mkdtemp(path.join(os.tmpdir(), 'fake-llm-ui-build-'));
  tempDirs.push(dataDir, webDirectory);
  await writeFile(path.join(webDirectory, 'index.html'), '<main>dashboard-shell</main>');
  await mkdir(path.join(webDirectory, 'assets'), { recursive: true });
  await writeFile(path.join(webDirectory, 'assets', 'app.js'), 'window.ready = true;');
  const store = await createStore({ dataDir });
  const app = createApp({ config: loadConfig({}), store, webDirectory });

  const page = await request(app).get('/');
  const asset = await request(app).get('/assets/app.js');
  const spaRoute = await request(app).get('/models');
  const apiRoot = await request(app).get('/api');
  const v1Root = await request(app).get('/v1');
  assert.equal(page.status, 200);
  assert.match(page.headers['content-type'], /text\/html/);
  assert.match(page.text, /dashboard-shell/);
  assert.equal(asset.status, 200);
  assert.match(asset.text, /window.ready/);
  assert.match(spaRoute.text, /dashboard-shell/);
  assert.equal(apiRoot.status, 404);
  assert.match(apiRoot.headers['content-type'], /application\/json/);
  assert.equal(v1Root.status, 404);
  assert.match(v1Root.headers['content-type'], /application\/json/);
});

