import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import express from 'express';
import request from 'supertest';
import test from 'node:test';
import { createAdminRouter } from '../server/routes/admin.js';
import { createStore } from '../server/store.js';
import { createMetrics } from '../server/metrics.js';

async function setup(run, { isProduction = false } = {}) {
  const dataDir = await mkdtemp(path.join(os.tmpdir(), 'fake-llm-admin-'));
  try {
    const store = await createStore({ dataDir });
    const metrics = createMetrics();
    const config = {
      adminUsername: 'admin',
      adminPassword: 'correct horse battery staple',
      adminSessionSecret: 'test-session-secret-long-enough',
      isProduction,
      minDelayMs: 10,
      maxDelayMs: 50,
    };
    const app = express();
    app.use(express.json());
    app.use('/api/admin', createAdminRouter({ store, config, metrics }));
    await run({ app, store, metrics });
  } finally {
    await rm(dataDir, { recursive: true, force: true });
  }
}

async function login(app) {
  const client = request.agent(app);
  const response = await client.post('/api/admin/login')
    .send({ username: 'admin', password: 'correct horse battery staple' })
    .expect(200);
  assert.equal(response.body.authenticated, true);
  assert.ok(response.body.csrfToken);
  return { client, csrfToken: response.body.csrfToken, cookie: response.headers['set-cookie'][0] };
}

test('admin routes require login, credentials are checked, and session cookie is protected', async () => {
  await setup(async ({ app }) => {
    await request(app).get('/api/admin/models').expect(401);
    await request(app).post('/api/admin/login').send({ username: 'admin', password: 'wrong' }).expect(401);

    const { client, csrfToken, cookie } = await login(app);
    assert.match(cookie, /HttpOnly/i);
    assert.match(cookie, /SameSite=Strict/i);
    assert.doesNotMatch(cookie, /Secure/i);
    await client.get('/api/admin/session').expect(200).expect(({ body }) => {
      assert.equal(body.authenticated, true);
      assert.equal(body.csrfToken, csrfToken);
    });
    await request(app).get('/api/admin/models').set('Cookie', cookie.replace(/;.*$/, '') + 'tampered').expect(401);
  });
});

test('production admin cookie is Secure and state changes require CSRF token', async () => {
  await setup(async ({ app }) => {
    const { csrfToken, cookie } = await login(app);
    assert.match(cookie, /Secure/i);
    const cookieValue = cookie.split(';', 1)[0];
    await request(app).post('/api/admin/models').set('Cookie', cookieValue)
      .send({ id: 'without-csrf' }).expect(403);
    await request(app).post('/api/admin/models').set('Cookie', cookieValue).set('X-CSRF-Token', csrfToken)
      .send({ id: 'with-csrf', name: 'With CSRF' }).expect(201);
  }, { isProduction: true });
});

test('API token secret is shown once, hash-only at rest, and can be revoked', async () => {
  await setup(async ({ app, store }) => {
    const { client, csrfToken } = await login(app);
    const created = await client.post('/api/admin/tokens').set('X-CSRF-Token', csrfToken)
      .send({ name: 'local tests' }).expect(201);
    assert.match(created.body.token, /^sk-mock-/);
    assert.equal(created.body.name, 'local tests');

    const records = await store.getApiTokens();
    assert.equal(records.length, 1);
    assert.notEqual(records[0].hash, created.body.token);
    assert.equal(JSON.stringify(records).includes(created.body.token), false);

    const listed = await client.get('/api/admin/tokens').expect(200);
    assert.equal(JSON.stringify(listed.body).includes(created.body.token), false);
    await client.delete(`/api/admin/tokens/${created.body.id}`).set('X-CSRF-Token', csrfToken).expect(204);
    assert.deepEqual(await store.getApiTokens(), []);
  });
});

test('settings validate and persist; activity summary is protected and counts requests', async () => {
  await setup(async ({ app, store, metrics }) => {
    const { client, csrfToken } = await login(app);
    await request(app).get('/api/admin/settings').expect(401);

    const defaults = await client.get('/api/admin/settings').expect(200);
    assert.equal(defaults.body.minDelayMs, 10);
    const updated = await client.put('/api/admin/settings').set('X-CSRF-Token', csrfToken)
      .send({ minDelayMs: 20, maxDelayMs: 40, chatTemplates: ['Proudly generated by a real model.'] })
      .expect(200);
    assert.equal(updated.body.minDelayMs, 20);
    assert.deepEqual(updated.body.chatTemplates, ['Proudly generated by a real model.']);
    assert.deepEqual(await store.getSettings(), updated.body);

    await client.put('/api/admin/settings').set('X-CSRF-Token', csrfToken)
      .send({ minDelayMs: 100, maxDelayMs: 20 }).expect(400);
    await client.put('/api/admin/settings').set('X-CSRF-Token', csrfToken)
      .send({ thinkingTemplates: [''] }).expect(400);

    metrics.record('/v1/chat/completions');
    metrics.record('/v1/chat/completions');
    metrics.record('/v1/responses');
    const summary = await client.get('/api/admin/summary').expect(200);
    assert.equal(summary.body.totalRequests, 3);
    assert.equal(summary.body.requestsByEndpoint['/v1/chat/completions'], 2);
    assert.equal(summary.body.requestsByEndpoint['/v1/responses'], 1);
    assert.ok(summary.body.lastRequestAt);
  });
});
