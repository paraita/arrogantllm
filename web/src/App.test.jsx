/** @vitest-environment jsdom */
import React from 'react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import App from './App.jsx';

const baseModel = {
  id: 'bright-model:7b', name: 'Bright Model 7B', active: true, source: 'manual',
  metadata: { task: { value: 'text-generation', provenance: 'published' }, contextLength: { value: 8192, provenance: 'published' } },
  createdAt: '2026-11-16T00:00:00.000Z', updatedAt: '2026-11-16T00:00:00.000Z',
};
const settings = {
  minDelayMs: 180, maxDelayMs: 900, streamChunkDelayMs: 120, thinkingEnabled: true,
  chatTemplates: ['Proudly generated by a real model. Probably.'],
  thinkingTemplates: ['I am thinking with convincing confidence.'],
};

function makeFetch() {
  let models = [{ ...baseModel }];
  let tokens = [];
  let config = { ...settings };
  let csrfToken = 'test-csrf';
  const calls = [];
  const fetch = vi.fn(async (input, init = {}) => {
    const url = new URL(input, window.location.origin);
    const method = init.method || 'GET';
    const body = init.body ? JSON.parse(init.body) : undefined;
    calls.push({ path: url.pathname, method, body, headers: Object.fromEntries(new Headers(init.headers || {}).entries()) });
    let data;
    let status = 200;
    if (url.pathname === '/api/admin/session') data = { authenticated: true, csrfToken };
    else if (url.pathname === '/api/admin/logout') data = null;
    else if (url.pathname === '/api/admin/models' && method === 'GET') data = { data: models };
    else if (url.pathname === '/api/admin/models' && method === 'POST') {
      const model = { ...body, active: false, source: 'manual', metadata: {}, createdAt: '2026-11-16T00:00:00.000Z' };
      models = [...models, model]; status = 201; data = model;
    } else if (url.pathname.startsWith('/api/admin/models/') && method === 'PATCH') {
      const id = decodeURIComponent(url.pathname.split('/').at(-1));
      models = models.map((item) => item.id === id ? { ...item, ...body } : item);
      data = models.find((item) => item.id === id);
    } else if (url.pathname === '/api/admin/tokens' && method === 'GET') data = { data: tokens };
    else if (url.pathname === '/api/admin/tokens' && method === 'POST') {
      const token = { id: 'new-token', name: body.name, prefix: 'sk-mock-abc', token: 'sk-mock-secret-once' };
      tokens = [...tokens, token]; status = 201; data = token;
    } else if (url.pathname.startsWith('/api/admin/tokens/') && method === 'DELETE') {
      tokens = tokens.filter((item) => item.id !== url.pathname.split('/').at(-1)); data = null;
    } else if (url.pathname === '/api/admin/settings' && method === 'GET') data = config;
    else if (url.pathname === '/api/admin/settings' && method === 'PUT') { config = { ...config, ...body }; data = config; }
    else if (url.pathname === '/api/admin/summary') data = { totalRequests: 17, lastRequestAt: '2026-11-16T00:00:00.000Z', requestsByEndpoint: { '/v1/chat/completions': 12, '/v1/models': 5 } };
    else if (url.pathname === '/api/admin/marketplaces/huggingface/search') {
      data = { data: [{ repoId: 'sample/bright-instruct', name: 'Bright Instruct', sourceUrl: 'https://huggingface.co/sample/bright-instruct', task: { value: 'text-generation', provenance: 'published' }, contextLength: { value: 8192, provenance: 'published' }, quantizer: { value: null, provenance: 'unknown' } }] };
    } else if (url.pathname === '/api/admin/marketplaces/huggingface/import' && method === 'POST') {
      status = 201; data = { ...baseModel, id: body.repoId, name: 'Bright Instruct', active: false, source: 'huggingface' };
    } else if (url.pathname === '/api/admin/login' && method === 'POST') { csrfToken = 'logged-in-csrf'; data = { authenticated: true, csrfToken }; }
    else { status = 404; data = { error: { message: 'Unknown route', type: 'not_found' } }; }
    return { ok: status < 400, status, json: async () => data };
  });
  return { fetch, calls };
}

describe('admin dashboard', () => {
  let api;
  beforeEach(() => {
    api = makeFetch();
    vi.stubGlobal('fetch', api.fetch);
    vi.stubGlobal('navigator', { ...navigator, clipboard: { writeText: vi.fn().mockResolvedValue(undefined) } });
  });
  afterEach(() => { cleanup(); vi.unstubAllGlobals(); });

  it('shows a login screen and signs in through the local admin route', async () => {
    api.fetch.mockImplementationOnce(async () => ({ ok: true, status: 200, json: async () => ({ authenticated: false, csrfToken: null }) }));
    render(<App />);
    expect(await screen.findByRole('heading', { name: /sign in to your console/i })).toBeTruthy();
    fireEvent.change(screen.getByLabelText(/username/i), { target: { value: 'admin' } });
    fireEvent.change(screen.getByLabelText(/password/i), { target: { value: 'local-secret' } });
    fireEvent.click(screen.getByRole('button', { name: /enter console/i }));
    expect((await screen.findAllByText(/simulation mode/i)).length).toBeGreaterThan(0);
    expect(api.calls.some((call) => call.path === '/api/admin/login' && call.method === 'POST')).toBe(true);
  });

  it('shows model metrics and toggles an active model with CSRF protection', async () => {
    render(<App />);
    expect(await screen.findByRole('heading', { name: /model overview/i })).toBeTruthy();
    expect(screen.getByText('17')).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: 'Models' }));
    const toggle = await screen.findByRole('checkbox', { name: /activate bright model 7b/i });
    fireEvent.click(toggle);
    await waitFor(() => expect(api.calls.some((call) => call.path === '/api/admin/models/bright-model%3A7b' && call.method === 'PATCH')).toBe(true));
    const patch = api.calls.find((call) => call.method === 'PATCH');
    expect(patch.headers['x-csrf-token']).toBe('test-csrf');
  });

  it('creates and edits a fake model', async () => {
    render(<App />);
    await screen.findByRole('heading', { name: /model overview/i });
    fireEvent.click(screen.getByRole('button', { name: 'Models' }));
    fireEvent.click(await screen.findByRole('button', { name: /add model/i }));
    fireEvent.change(screen.getByLabelText(/model id/i), { target: { value: 'comedy-model:3b' } });
    fireEvent.change(screen.getByLabelText(/display name/i), { target: { value: 'Comedy Model 3B' } });
    fireEvent.click(screen.getByRole('button', { name: /save model/i }));
    expect(await screen.findByText(/comedy-model:3b/i)).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /edit comedy model 3b/i }));
    fireEvent.change(screen.getByLabelText(/display name/i), { target: { value: 'Comedy Model Updated' } });
    fireEvent.click(screen.getByRole('button', { name: /save model/i }));
    expect(await screen.findByText(/comedy model updated/i)).toBeTruthy();
  });

  it('searches and imports a marketplace model as inactive', async () => {
    render(<App />);
    await screen.findByRole('heading', { name: /model overview/i });
    fireEvent.click(screen.getByRole('button', { name: 'Marketplace' }));
    fireEvent.change(await screen.findByLabelText(/search models/i), { target: { value: 'bright instruct' } });
    fireEvent.click(screen.getByRole('button', { name: /search hub/i }));
    expect(await screen.findByText(/sample\/bright-instruct/i)).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /import as inactive/i }));
    expect(await screen.findByText(/model imported and left inactive/i)).toBeTruthy();
    expect(api.calls.some((call) => call.path.endsWith('/marketplaces/huggingface/import') && call.headers['x-csrf-token'] === 'test-csrf')).toBe(true);
  });

  it('saves delay, thinking and humor templates', async () => {
    render(<App />);
    await screen.findByRole('heading', { name: /model overview/i });
    fireEvent.click(screen.getByRole('button', { name: 'Settings' }));
    fireEvent.change(await screen.findByLabelText(/minimum delay/i), { target: { value: '250' } });
    fireEvent.change(screen.getByLabelText(/maximum delay/i), { target: { value: '1400' } });
    fireEvent.change(screen.getByLabelText(/response templates/i), { target: { value: 'A real model did this. Probably.' } });
    fireEvent.click(screen.getByRole('button', { name: /save settings/i }));
    expect(await screen.findByText(/settings saved/i)).toBeTruthy();
    const save = api.calls.find((call) => call.path === '/api/admin/settings' && call.method === 'PUT');
    expect(save.body.minDelayMs).toBe(250);
    expect(save.body.chatTemplates).toEqual(['A real model did this. Probably.']);
  });

  it('shows new API token only once and confirms before revoking', async () => {
    render(<App />);
    await screen.findByRole('heading', { name: /model overview/i });
    fireEvent.click(screen.getByRole('button', { name: /api tokens/i }));
    fireEvent.change(await screen.findByLabelText(/token name/i), { target: { value: 'Local app' } });
    fireEvent.click(screen.getByRole('button', { name: /create token/i }));
    expect(await screen.findByText('sk-mock-secret-once')).toBeTruthy();
    expect(screen.getAllByText(/shown only once/i).length).toBeGreaterThan(0);
    fireEvent.click(screen.getByRole('button', { name: /done/i }));
    fireEvent.click(await screen.findByRole('button', { name: /revoke local app/i }));
    expect(await screen.findByRole('alertdialog')).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /confirm revoke/i }));
    await waitFor(() => expect(api.calls.some((call) => call.path === '/api/admin/tokens/new-token' && call.method === 'DELETE')).toBe(true));
  });
});
